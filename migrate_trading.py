def load_env(path: Path) -> None:
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, value = line.split("=", 1)
        os.environ.setdefault(name.strip(), value.strip().strip('"').strip("'"))


def required(name: str) -> str:
    value = os.environ.get(name)
    if not value:
        raise SystemExit(f"Missing required setting: {name}")
    return value


def migrations() -> list[tuple[str, str]]:
    result = []
    for item in required("MSSQL_MIGRATIONS").split(","):
        parts = [part.strip() for part in item.split(":")]
        if len(parts) != 2 or not all(parts):
            raise SystemExit(
                "Invalid MSSQL_MIGRATIONS; expected database:schema pairs"
            )
        result.append((parts[0], parts[1]))
    if len({schema for _, schema in result}) != len(result):
        raise SystemExit("Invalid MSSQL_MIGRATIONS; target schemas must be unique")
    return result


def clear_protected_databases() -> set[str]:
    return {
        database.strip().casefold()
        for database in os.getenv("MSSQL_CLEAR_PROTECTED", "").split(",")
        if database.strip()
    }


def clear_protected_actions(data: dict[str, list[tuple]]) -> None:
    data["actions"] = [row[:-1] + (False,) for row in data["actions"]]


def mssql_connection(database: str):
    import pymssql

    return pymssql.connect(
        server=required("MSSQL_HOST"),
        port=int(required("MSSQL_PORT")),
        user=required("MSSQL_USER"),
        password=required("MSSQL_PASSWORD"),
        database=database,
        tds_version="7.0",
        charset="cp1251",
        login_timeout=10,
        timeout=60,
    )


def pg_connection():
    import psycopg

    return psycopg.connect(
        host=required("LOCAL_PGSQL_HOST"),
        port=int(required("LOCAL_PGSQL_PORT")),
        user=required("LOCAL_PGSQL_USER"),
        password=required("LOCAL_PGSQL_PASSWORD"),
        dbname=required("LOCAL_PGSQL_DATABASE"),
    )


def select_schema(cursor, schema: str) -> None:
    from psycopg import sql

    cursor.execute(
        sql.SQL("SET LOCAL search_path TO {}, pg_catalog").format(
            sql.Identifier(schema)
        )
    )


def read_source(database: str) -> dict[str, list[tuple]]:
    data: dict[str, list[tuple]] = {}
    with mssql_connection(database) as connection:
        cursor = connection.cursor()
        for table in TABLES:
            cursor.execute(f"SELECT {table.select} FROM [{table.source}] ORDER BY ID")
            data[table.target] = list(cursor.fetchall())
    return data


def remove_unused_references(data: dict[str, list[tuple]]) -> dict[str, int]:
    actions = data["actions"]
    used = {
        "accounts": {row[1] for row in actions},
        "suboperations_l2": {row[2] for row in actions},
        "currencies": {row[3] for row in actions},
    }

    data["accounts"] = [row for row in data["accounts"] if row[0] in used["accounts"]]
    used["currencies"].update(row[2] for row in data["accounts"])
    data["suboperations_l2"] = [
        row for row in data["suboperations_l2"] if row[0] in used["suboperations_l2"]
    ]
    for child, parent, fk_index in (
        ("suboperations_l2", "suboperations_l1", 1),
        ("suboperations_l1", "action_types", 1),
        ("action_types", "directions", 1),
    ):
        parent_ids = {row[fk_index] for row in data[child] if row[fk_index] is not None}
        data[parent] = [row for row in data[parent] if row[0] in parent_ids]
    data["currencies"] = [
        row for row in data["currencies"] if row[0] in used["currencies"]
    ]
    data["currency_rates"] = [
        row for row in data["currency_rates"] if row[1] in used["currencies"]
    ]

    return {table.target: len(data[table.target]) for table in TABLES}


def add_placeholders(data: dict[str, list[tuple]]) -> dict[str, list[int]]:
    placeholders: dict[str, list[int]] = {}

    def fill(child: str, parent: str, fk_index: int) -> None:
        parent_ids = {row[0] for row in data[parent]}
        missing = sorted(
            {row[fk_index] for row in data[child] if row[fk_index] is not None}
            - parent_ids
        )
        if not missing:
            return
        if parent == "directions":
            generated = (
                (item_id, f"[missing legacy ID {item_id}]", "Generated during migration")
                for item_id in missing
            )
        else:
            generated = (
                (
                    item_id,
                    None,
                    f"[missing legacy ID {item_id}]",
                    "Generated during migration",
                )
                for item_id in missing
            )
        data[parent].extend(generated)
        data[parent].sort(key=lambda row: row[0])
        placeholders[parent] = missing

    fill("action_types", "directions", 1)
    fill("suboperations_l1", "action_types", 1)
    fill("suboperations_l2", "suboperations_l1", 1)
    fill("actions", "suboperations_l2", 2)
    return placeholders


def converted_rows(table: str, rows: list[tuple], placeholders: set[int]):
    for row in rows:
        values = list(row)
        if table in {
            "directions",
            "action_types",
            "suboperations_l1",
            "suboperations_l2",
        }:
            values.append(values[0] in placeholders)
        elif table == "currency_rates":
            values[3] = Decimal(str(values[3])) if values[3] is not None else None
        elif table == "legacy_users":
            values[3] = bool(values[3]) if values[3] is not None else None
        elif table == "actions":
            values[4] = Decimal(str(values[4])) if values[4] is not None else None
            values[6] = Decimal(str(values[6])) if values[6] is not None else None
            values[7] = bool(values[7]) if values[7] is not None else None
            values[9] = bool(values[9]) if values[9] is not None else None
        yield tuple(values)


def copy_table(cursor, table: Table, rows: list[tuple], placeholders: set[int]) -> None:
    columns = table.columns
    if table.target in {
        "directions",
        "action_types",
        "suboperations_l1",
        "suboperations_l2",
    }:
        columns += ("is_placeholder",)
    statement = f"COPY {table.target} ({', '.join(columns)}) FROM STDIN"
    with cursor.copy(statement) as copy:
        for row in converted_rows(table.target, rows, placeholders):
            copy.write_row(row)


def reset_sequences(cursor) -> None:
    for table in TABLES:
        cursor.execute(
            f"""
            SELECT setval(
                pg_get_serial_sequence('{table.target}', 'id'),
                COALESCE(MAX(id), 1),
                COUNT(*) > 0
            )
            FROM {table.target}
            """
        )


def validate(cursor, data: dict[str, list[tuple]]) -> None:
    for table in TABLES:
        cursor.execute(f"SELECT COUNT(*) FROM {table.target}")
        actual = cursor.fetchone()[0]
        expected = len(data[table.target])
        if actual != expected:
            raise RuntimeError(
                f"Row count mismatch for {table.target}: {actual} != {expected}"
            )


def check(
    data: dict[str, list[tuple]],
    placeholders: dict[str, list[int]],
    database: str,
    schema: str,
) -> None:
    with pg_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute("SELECT current_database(), current_setting('server_version')")
            pg_database, version = cursor.fetchone()
    print(
        f"MSSQL database={database} -> PostgreSQL {version}, "
        f"database={pg_database}, schema={schema}"
    )
    for table in TABLES:
        print(f"{table.source:18} -> {table.target:18} {len(data[table.target]):>7} rows")
    for table, ids in placeholders.items():
        print(f"placeholder {table}: {', '.join(map(str, ids))}")


def apply(
    data: dict[str, list[tuple]], placeholders: dict[str, list[int]], schema: str
) -> None:
    from psycopg import sql

    with pg_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(
                    sql.Identifier(schema)
                )
            )
            select_schema(cursor, schema)
            cursor.execute(
                "SELECT pg_advisory_xact_lock(hashtext(%s))",
                (f"{required('LOCAL_PGSQL_DATABASE')}.{schema}.migration",),
            )
            cursor.execute(DDL)
            cursor.execute(
                "TRUNCATE actions, currency_rates, legacy_users, accounts, currencies, "
                "suboperations_l2, suboperations_l1, action_types, directions "
                "RESTART IDENTITY CASCADE"
            )
            for table in TABLES:
                copy_table(
                    cursor,
                    table,
                    data[table.target],
                    set(placeholders.get(table.target, ())),
                )
            reset_sequences(cursor)
            validate(cursor, data)
    print("Migration committed successfully")


def main() -> None:
    parser = argparse.ArgumentParser(description="Migrate MSSQL trading to PostgreSQL")
    parser.add_argument("--env", type=Path, default=Path(".env"))
    parser.add_argument(
        "--apply",
        action="store_true",
        help="replace the managed PostgreSQL tables; default is read-only check",
    )
    args = parser.parse_args()
    load_env(args.env)
    databases_without_protected = clear_protected_databases()
    for database, schema in migrations():
        print(f"\n{database} -> {schema}")
        data = read_source(database)
        if database.casefold() in databases_without_protected:
            clear_protected_actions(data)
            print("protected action flags cleared")
        source_counts = {table.target: len(data[table.target]) for table in TABLES}
        kept_counts = remove_unused_references(data)
        for table in TABLES:
            removed = source_counts[table.target] - kept_counts[table.target]
            if removed:
                print(f"unused {table.target}: {removed} rows skipped")
        placeholders = add_placeholders(data)
        if args.apply:
            apply(data, placeholders, schema)
        else:
            check(data, placeholders, database, schema)


if __name__ == "__main__":
    main()
